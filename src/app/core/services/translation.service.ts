  readonly isRtl = computed(() => this.currentLang() === 'ar');

  toggleLanguage(): void {
    const newLang: Lang = this.currentLang() === 'ar' ? 'en' : 'ar';
    this.currentLang.set(newLang);
    localStorage.setItem(this.languageStorageKey, newLang);
    this.applyDocumentLanguage(newLang);
  }

  private getStoredLanguage(): Lang {
    const storedLanguage = localStorage.getItem(this.languageStorageKey);
    return storedLanguage === 'en' || storedLanguage === 'ar' ? storedLanguage : 'ar';
  }

  private applyDocumentLanguage(lang: Lang): void {
    document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';
    document.documentElement.lang = lang;
  }

  translate(key: string): string {
    const lang = this.currentLang();
    return this.translations[lang]?.[key] || key;
  }
